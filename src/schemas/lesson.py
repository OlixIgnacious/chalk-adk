"""Pydantic schemas defining the data contract for Chalk-ADK Interactive Lessons, HyperFrames scenes, and Learner audits."""

from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class SourceReference(BaseModel):
    """Grounding reference pointing directly to the original source text."""
    file_name: str = Field(description="Name or path of source file")
    section_title: Optional[str] = Field(default=None, description="Section or chapter heading")
    excerpt: str = Field(description="Exact verbatim excerpt from source validating the claim")
    line_start: Optional[int] = Field(default=None, description="Starting line in source if available")
    line_end: Optional[int] = Field(default=None, description="Ending line in source if available")


class VisualDirective(BaseModel):
    """Specification of visuals rendered on the interactive board for a segment."""
    kind: Literal["markdown", "code", "diagram", "comparison", "callout"] = Field(
        default="markdown",
        description="Type of visual content"
    )
    title: str = Field(description="Title or heading for this visual block")
    content: str = Field(description="Markdown, code content, or Mermaid diagram syntax")
    language: Optional[str] = Field(default="python", description="Programming or markup language for code blocks")
    highlight_lines: List[int] = Field(default_factory=list, description="Lines to emphasize/glow")


class HyperFrameScene(BaseModel):
    """Animated scene composition for HyperFrames (HTML + CSS + GSAP timeline)."""
    html: str = Field(
        description="Semantic HTML markup for the 16:9 scene (macOS terminal window, animated cards, flow nodes)"
    )
    css: Optional[str] = Field(
        default="",
        description="Optional scoped CSS rules or utility styling"
    )
    gsap_timeline: str = Field(
        description="JavaScript GSAP animation timeline script animating visual elements in sync with audio"
    )


class CheckpointOption(BaseModel):
    """An option in an interactive checkpoint question."""
    id: str = Field(description="Letter identifier, e.g., 'A', 'B', 'C', 'D'")
    text: str = Field(description="The option text")
    is_correct: bool = Field(description="True if this is the correct answer")
    explanation: str = Field(
        description="Grounded explanation shown immediately after learner selects this option"
    )


class CheckpointQuestion(BaseModel):
    """An interactive checkpoint halting playback to verify comprehension."""
    id: str = Field(description="Unique question identifier, e.g., 'q1'")
    prompt: str = Field(description="The question or puzzle prompt presented to the learner")
    question_type: Literal["multiple_choice", "code_prediction", "true_false"] = Field(
        default="multiple_choice",
        description="Type of interaction"
    )
    options: List[CheckpointOption] = Field(description="List of choices (typically 3-4 options)")
    hint: Optional[str] = Field(default=None, description="Optional gentle nudge if student is stuck")
    source_grounding: SourceReference = Field(
        description="Direct citation verifying the correct answer and debunking distractors"
    )


class LessonSegment(BaseModel):
    """A bite-sized learning segment with spoken narration, HyperFrames scene, and a checkpoint."""
    id: str = Field(description="Segment identifier, e.g., 'seg-1'")
    order: int = Field(description="Sequence position (1-based)")
    title: str = Field(description="Segment title (e.g. 'Understanding Attention Weights')")
    narration: str = Field(
        description="Conversational, precise spoken narration text for Kokoro TTS (approx. 100-180 words, ~45-75s)"
    )
    hyperframe: Optional[HyperFrameScene] = Field(
        default=None,
        description="Animated HyperFrames scene composition with HTML and GSAP timeline"
    )
    visuals: List[VisualDirective] = Field(
        default_factory=list,
        description="Fallback visual directives (markdown, code, diagram)"
    )
    checkpoint: CheckpointQuestion = Field(
        description="Mandatory comprehension checkpoint before advancing to the next segment"
    )
    source_citations: List[SourceReference] = Field(
        default_factory=list,
        description="Passages from source text backing the segment's core statements"
    )
    audio_file: Optional[str] = Field(
        default=None,
        description="Relative path to generated audio file (populated during build stage)"
    )


class OutlineUnit(BaseModel):
    """Planned outline unit during curriculum curation."""
    unit_number: int
    title: str
    core_concept: str
    key_takeaway: str
    estimated_seconds: int = 60


class CurriculumOutline(BaseModel):
    """Pedagogical outline generated by CuratorAgent from raw source text."""
    title: str = Field(description="Engaging, clear title of the lesson")
    target_audience: str = Field(default="Developers / Learners", description="Intended audience level")
    learning_objectives: List[str] = Field(
        description="3-5 concrete measurable learning objectives (Bloom's taxonomy)"
    )
    units: List[OutlineUnit] = Field(
        description="3 to 5 progressive units breaking down the subject"
    )


class VerificationIssue(BaseModel):
    """Factual issue flagged during fact-checking."""
    severity: Literal["critical", "warning", "info"] = "warning"
    location: str = Field(description="Segment or question ID where issue was found")
    claim: str = Field(description="The questionable statement or question element")
    issue_description: str = Field(description="Why this is ungrounded or misleading")
    suggested_fix: str = Field(description="Corrective action or revised wording")


class LearnerFrictionIssue(BaseModel):
    """Pedagogical friction issue flagged by the chalk-learner persona audit."""
    segment_order: int = Field(description="Segment number where friction occurs")
    issue_type: Literal[
        "undefined_jargon",
        "abrupt_transition",
        "cognitive_overload",
        "ambiguous_question",
        "pacing_imbalance"
    ] = Field(description="Category of pedagogical friction")
    description: str = Field(description="Why a student would get confused or stumble here")
    recommendation: str = Field(description="How to smooth out the explanation or rephrase")


class LearnerFrictionAudit(BaseModel):
    """Chalk-Learner audit evaluating pedagogical smoothness and cognitive friction."""
    friction_score: float = Field(ge=0.0, le=1.0, description="Pedagogical clarity score (1.0 = seamless, <0.7 = friction)")
    reading_level: str = Field(default="Intermediate Developer", description="Target comprehension level")
    cognitive_load: Literal["low", "balanced", "high"] = Field(default="balanced", description="Assessment of concept density")
    friction_issues: List[LearnerFrictionIssue] = Field(default_factory=list, description="Specific stumbling blocks")
    pedagogical_summary: str = Field(description="Holistic evaluation from a learner's point of view")


class VerificationReport(BaseModel):
    """Unified quality, grounding, and chalk-learner audit report."""
    is_grounded: bool = Field(description="True if all claims are backed by source")
    factual_score: float = Field(ge=0.0, le=1.0, description="Confidence score (0.0 - 1.0)")
    issues: List[VerificationIssue] = Field(default_factory=list, description="Factual issues")
    learner_audit: Optional[LearnerFrictionAudit] = Field(
        default=None,
        description="Chalk-Learner pedagogical friction assessment"
    )
    summary: str = Field(description="Brief assessment of pedagogical flow and accuracy")


class LessonSpec(BaseModel):
    """Full specification for compiling an interactive lesson, video scenes, and notebook."""
    lesson_id: str = Field(description="Kebab-case unique id (e.g., 'attention-mechanism-101')")
    title: str = Field(description="Main lesson title")
    subtitle: str = Field(description="Short engaging subtitle")
    estimated_duration_minutes: int = Field(default=5, description="Total expected completion time")
    learning_objectives: List[str] = Field(description="Key takeaways")
    segments: List[LessonSegment] = Field(description="Ordered list of learning segments")
    summary: str = Field(description="Final concluding takeaway or next steps")
    source_file: str = Field(description="Path to the primary source document used")
    verification_report: Optional[VerificationReport] = Field(
        default=None,
        description="Verification audit from GroundingAgent and LearnerAudit"
    )
